/// Where `--inject-uuid` writes the ProGuard UUID, relative to the project
/// root. The Android Gradle Plugin packages it into the app's assets, and the
/// Sentry Android SDK reads it from there at startup.
const debugMetaAssetPath =
    'android/app/src/main/assets/sentry-debug-meta.properties';

const _proguardUuidsKey = 'io.sentry.ProguardUuids';
const _injectedMarker =
    '# Generated by sentry_dart_plugin --inject-uuid. Removed after the upload.';

/// A built APK or AAB and the ProGuard UUID inside it, if any.
class BuiltAppProguardUuid {
  final String? uuid;
  final String artifactPath;

  BuiltAppProguardUuid(this.uuid, this.artifactPath);
}

/// Generates a random (version 4) UUID.
String generateUuid() {
  final random = Random.secure();
  final bytes = List<int>.generate(16, (_) => random.nextInt(256));
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  final hex = bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
  return '${hex.substring(0, 8)}-${hex.substring(8, 12)}-'
      '${hex.substring(12, 16)}-${hex.substring(16, 20)}-${hex.substring(20)}';
}

/// Returns the first UUID of `io.sentry.ProguardUuids` in the properties
/// [content], or null.
String? parseProguardUuid(String content) {
  for (final rawLine in const LineSplitter().convert(content)) {
    final line = rawLine.trim();
    if (line.isEmpty || line.startsWith('#') || line.startsWith('!')) {
      continue;
    }
    // Java properties separate key and value by '=', ':' or whitespace.
    final match =
        RegExp(r'^([^=:\s]+)(?:\s*[=:]\s*|\s+)(.*)$').firstMatch(line);
    if (match == null || match.group(1) != _proguardUuidsKey) {
      continue;
    }
    // Several UUIDs may be separated by '|'; the SDK uses the first one.
    final uuid = match.group(2)!.split('|').first.trim();
    return uuid.isEmpty ? null : uuid;
  }
  return null;
}

/// Runs `--inject-uuid`: writes a ProGuard UUID into [debugMetaAssetPath] so
/// the next `flutter build` packages it into the app. Uses the configured
/// `proguard_uuid` if set, otherwise generates one. Returns the exit code.
///
/// Warns to add the file to `.gitignore` when git reports it isn't ignored.
Future<int> injectProguardUuid({
  required FileSystem fs,
  required Configuration config,
  required ProcessManager processManager,
}) async {
  const taskName = 'injecting ProGuard UUID';
  Log.startingTask(taskName);
  try {
    if (!config.uploadProguard) {
      Log.info('uploadProguard is disabled, not injecting a ProGuard UUID.');
      return 0;
    }

    if (!await fs.directory('android/app').exists()) {
      Log.info('No Android app found (android/app), nothing to inject.');
      return 0;
    }

    final gradlePluginFile = await _findSentryGradlePlugin(fs);
    if (gradlePluginFile != null) {
      Log.warn(
          "The Sentry Android Gradle Plugin is applied in '$gradlePluginFile'. "
          'It already generates and uploads the ProGuard UUID, so --inject-uuid '
          'does nothing.');
      return 0;
    }

    final configured = config.proguardUuid?.trim() ?? '';
    final file = fs.file(debugMetaAssetPath);
    if (await file.exists() && !await _isInjectedByPlugin(file)) {
      // .properties files are ISO-8859-1 by spec.
      final existing =
          parseProguardUuid(latin1.decode(await file.readAsBytes()));
      if (existing == null) {
        Log.warn(
            "'$debugMetaAssetPath' exists and was not created by this plugin, "
            'not modifying it. Add $_proguardUuidsKey=<uuid> to it yourself, '
            'or remove the file.');
        return 0;
      }
      if (configured.isNotEmpty &&
          configured.toLowerCase() != existing.toLowerCase()) {
        Log.error("'$debugMetaAssetPath' sets ProGuard UUID $existing, but "
            "'proguard_uuid' is $configured. The app would report $existing "
            'while the mapping is uploaded under $configured. Remove one of '
            'them.');
        return 1;
      }
      Log.info("'$debugMetaAssetPath' already sets ProGuard UUID $existing and "
          'was not created by this plugin, leaving it as is. The upload '
          'will use it.');
      return 0;
    }

    if (configured.isNotEmpty && !isValidProguardUuid(configured)) {
      Log.error("'proguard_uuid' is not a valid UUID: '$configured'.");
      return 1;
    }
    final uuid = configured.isNotEmpty ? configured : generateUuid();

    await file.parent.create(recursive: true);
    await file.writeAsString('$_injectedMarker\n$_proguardUuidsKey=$uuid\n');

    final source = configured.isNotEmpty ? 'Using the configured' : 'Generated';
    Log.info("$source ProGuard UUID $uuid and injected it into "
        "'$debugMetaAssetPath'. Now run flutter build, then "
        'dart run sentry_dart_plugin to upload the mapping.');
    if (await _isNotGitIgnored(processManager)) {
      Log.warn("Add '$debugMetaAssetPath' to your .gitignore so it isn't "
          'committed by accident. The plugin removes it after the upload.');
    }
    return 0;
  } on FileSystemException catch (e) {
    Log.error('Failed to inject the ProGuard UUID: $e');
    return 1;
  } finally {
    Log.taskCompleted(taskName);
  }
}

/// Whether git says [debugMetaAssetPath] isn't ignored (`git check-ignore`
/// exits with 1). False if it is ignored, or if that can't be told: not a git
/// repository (128), git isn't installed, etc. Never throws.
Future<bool> _isNotGitIgnored(ProcessManager processManager) async {
  try {
    final result = await processManager
        .run(['git', 'check-ignore', '-q', debugMetaAssetPath]);
    return result.exitCode == 1;
  } on ProcessException {
    return false;
  }
}

/// Reads the ProGuard UUID from the most recent release-type APK or AAB under
/// `<build_path>/app/outputs` (a later debug build doesn't count). Returns
/// null without such an APK/AAB.
///
/// For the explicit [mappingPath], when it is the mapping of a variant under
/// `<build_path>/app/outputs/mapping/<variant>/`, only APKs/AABs of that
/// variant count: another flavor built later reports another UUID.
Future<BuiltAppProguardUuid?> readBuiltAppProguardUuid({
  required FileSystem fs,
  required Configuration config,
  String? mappingPath,
}) async {
  final variant = mappingPath == null
      ? null
      : _builtMappingVariant(fs, config, mappingPath)?.toLowerCase();
  try {
    for (final artifact in await _listArtifacts(fs, config)) {
      if (artifact.isUnminified ||
          (variant != null && artifact.variant.toLowerCase() != variant)) {
        continue;
      }
      return BuiltAppProguardUuid(await artifact.uuid(), artifact.file.path);
    }
  } on FileSystemException catch (e) {
    Log.warn('Could not look for the built APK/AAB: $e');
  }
  return null;
}

/// The variant of [mappingPath] if it is
/// `<build_path>/app/outputs/mapping/<variant>/mapping.txt`, else null.
String? _builtMappingVariant(
    FileSystem fs, Configuration config, String mappingPath) {
  final mappingDir = fs.path.normalize(fs.path.absolute(
      fs.path.join(config.buildFilesFolder, 'app', 'outputs', 'mapping')));
  final file = fs.path.normalize(fs.path.absolute(mappingPath));
  final variantDir = fs.path.dirname(file);
  if (fs.path.basename(file) != 'mapping.txt' ||
      !fs.path.equals(fs.path.dirname(variantDir), mappingDir)) {
    return null;
  }
  return fs.path.basename(variantDir);
}

/// The most recent minified (release-type) APK/AAB and the mapping its build
/// wrote, see [findLastReleaseBuild].
class LastReleaseBuild {
  final String artifactPath;

  /// The ProGuard UUID packaged into it, if any.
  final String? uuid;

  /// The mapping of its variant (`apk/free/release/` -> `freeRelease`),
  /// or null if there is none or it was written after this build, i.e. none
  /// of the discovered mappings belongs to it.
  final ProguardMapping? mapping;

  /// When [mapping] is null: the mapping of its variant, which was written
  /// after this build (e.g. by a later build that failed), if any.
  final ProguardMapping? staleMapping;

  LastReleaseBuild(this.artifactPath, this.uuid, this.mapping,
      [this.staleMapping]);
}

/// Finds the most recent minified APK/AAB under `<build_path>/app/outputs`
/// (debug and profile builds aren't minified) and, among [mappings], the one
/// its build wrote. Returns null without such an APK/AAB.
///
/// The mapping is matched by variant only, never by recency: R8 doesn't
/// rewrite a mapping that is up to date, so another variant's may be newer,
/// and a leftover mapping of another variant must not be uploaded for a build
/// that wasn't minified. Older APKs/AABs are not considered: in a reused build
/// directory they may belong to another variant than the one just built.
Future<LastReleaseBuild?> findLastReleaseBuild({
  required FileSystem fs,
  required Configuration config,
  required List<ProguardMapping> mappings,
}) async {
  try {
    for (final artifact in await _listArtifacts(fs, config)) {
      if (artifact.isUnminified) {
        continue;
      }
      final own = mappings.where(
          (m) => m.variant?.toLowerCase() == artifact.variant.toLowerCase());
      final mapping = own.isEmpty ? null : own.first;
      final isStale = mapping?.builtAt != null &&
          artifact.modified.isBefore(mapping!.builtAt!);
      return LastReleaseBuild(artifact.file.path, await artifact.uuid(),
          isStale ? null : mapping, isStale ? mapping : null);
    }
  } on FileSystemException catch (e) {
    Log.warn('Could not look for the built APK/AAB: $e');
  }
  return null;
}

/// When `--inject-uuid` wrote its file, or null if it isn't there.
Future<DateTime?> injectedProguardUuidTime(FileSystem fs) async {
  if (!await hasInjectedProguardUuid(fs)) {
    return null;
  }
  try {
    return await fs.file(debugMetaAssetPath).lastModified();
  } on FileSystemException {
    return null;
  }
}

/// Whether `--inject-uuid` left its file in the project.
Future<bool> hasInjectedProguardUuid(FileSystem fs) async {
  final file = fs.file(debugMetaAssetPath);
  try {
    return await file.exists() && await _isInjectedByPlugin(file);
  } on FileSystemException {
    return false;
  }
}

/// The release-type variants (e.g. `freeRelease`) built since
/// `--inject-uuid` that packaged its UUID. More than one means several builds
/// share the UUID, so no single mapping matches it. The ABI splits of a
/// variant (`--split-per-abi`) and its unsigned build share one mapping, so
/// they count as one.
Future<Set<String>> variantsBuiltWithInjectedUuid({
  required FileSystem fs,
  required Configuration config,
}) async {
  final injectedAt = await injectedProguardUuidTime(fs);
  if (injectedAt == null) {
    return {};
  }
  final injected = parseProguardUuid(
      latin1.decode(await fs.file(debugMetaAssetPath).readAsBytes()));
  if (injected == null) {
    // Edited by hand: no build can be told to have packaged it.
    return {};
  }
  final variants = <String>{};
  for (final artifact in await _listArtifacts(fs, config)) {
    if (!artifact.modified.isAfter(injectedAt)) {
      break;
    }
    if (artifact.isUnminified) {
      continue;
    }
    if ((await artifact.uuid())?.toLowerCase() == injected.toLowerCase()) {
      if (!variants
          .any((v) => v.toLowerCase() == artifact.variant.toLowerCase())) {
        variants.add(artifact.variant);
      }
    }
  }
  return variants;
}

/// Removes the file written by `--inject-uuid` once a release build has
/// packaged it, i.e. when a release-type APK/AAB newer than the file contains
/// its UUID. This way a later build without `--inject-uuid` can't silently
/// reuse the UUID with a different mapping, while a run for another platform,
/// a debug build, or a run before the release build leaves it in place.
///
/// Files not created by this plugin are left untouched. Never throws.
Future<void> removeConsumedInjectedProguardUuid({
  required FileSystem fs,
  required Configuration config,
}) async {
  try {
    if ((await variantsBuiltWithInjectedUuid(fs: fs, config: config)).isEmpty) {
      return;
    }
    await fs.file(debugMetaAssetPath).delete();
    Log.info("Removed '$debugMetaAssetPath'. Run --inject-uuid again before "
        'the next build.');
  } on FileSystemException catch (e) {
    Log.warn("Could not remove '$debugMetaAssetPath': $e");
  }
}

/// `[free, release]` -> `freeRelease`.
String _camelCase(List<String> parts) {
  final words = parts.where((p) => p.isNotEmpty).toList();
  if (words.isEmpty) {
    return '';
  }
  return words.first +
      words.skip(1).map((w) => w[0].toUpperCase() + w.substring(1)).join();
}

/// The ABI part of a `--split-per-abi` APK name, and `-unsigned`.
final _abiOrUnsigned = RegExp(
    r'-(armeabi-v7a|armeabi|arm64-v8a|x86_64|x86|mips64|mips|universal|unsigned)(?=-|$)');

class _Artifact {
  final File file;
  final DateTime modified;

  /// The directories between `<build_path>/app/outputs` and the file, e.g.
  /// `[apk, free, release]`, `[bundle, freeRelease]` or `[flutter-apk]`.
  final List<String> _dirs;
  String? _uuid;
  var _read = false;

  _Artifact(this.file, this.modified, this._dirs);

  String get _name => file.basename.toLowerCase();

  /// The Gradle variant it was built from (`release`, `freeRelease`), which
  /// is also the name of its mapping directory. The APK/AAB, the ABI splits
  /// (`--split-per-abi`) and the unsigned build of a variant share it, as they
  /// share its one mapping.
  ///
  /// Taken from the directory the Android Gradle Plugin writes to
  /// (`apk/<flavor>/<buildType>/`, `bundle/<variant>/`), so that renamed
  /// outputs (`archivesBaseName`, `outputFileName`) still match. Only
  /// Flutter's copies (`flutter-apk/app-free-release.apk`), whose names
  /// Flutter sets, are matched by file name.
  String get variant {
    if (_dirs.length >= 2 && _dirs.first == 'bundle') {
      return _dirs.last;
    }
    if (_dirs.length >= 2 && _dirs.first == 'apk') {
      return _camelCase(_dirs.sublist(1));
    }
    final stem = _name
        .substring(0, _name.lastIndexOf('.'))
        .replaceAll(_abiOrUnsigned, '');
    if (!stem.startsWith('app-')) {
      // Not named by Flutter (e.g. `app.apk` of old Flutter versions or
      // custom tooling): the variant can't be told.
      return '';
    }
    return _camelCase(stem.substring('app-'.length).split('-'));
  }

  /// An instrumentation test APK (`apk/androidTest/...`,
  /// `app-debug-androidTest.apk`), not the app.
  bool get _isTest =>
      _dirs.any((d) => d.toLowerCase() == 'androidtest') ||
      _name.contains('-androidtest');

  /// Not known to be a release-type build of the app: a test APK, a debug or
  /// profile build (which Flutter doesn't minify), or one whose variant can't
  /// be told.
  bool get isUnminified {
    final lower = variant.toLowerCase();
    return lower.isEmpty ||
        _isTest ||
        lower.endsWith('debug') ||
        lower.endsWith('profile');
  }

  Future<String?> uuid() async {
    if (!_read) {
      _read = true;
      final entryName = _name.endsWith('.aab')
          ? 'base/assets/sentry-debug-meta.properties'
          : 'assets/sentry-debug-meta.properties';
      try {
        final bytes = await readZipEntry(file, entryName);
        _uuid = bytes == null ? null : parseProguardUuid(latin1.decode(bytes));
      } on FileSystemException catch (e) {
        Log.warn("Could not read '${file.path}': $e");
      }
    }
    return _uuid;
  }
}

/// The APKs/AABs under `<build_path>/app/outputs`, the most recent first.
Future<List<_Artifact>> _listArtifacts(
    FileSystem fs, Configuration config) async {
  final outputs =
      fs.directory(fs.path.join(config.buildFilesFolder, 'app', 'outputs'));
  if (!await outputs.exists()) {
    return [];
  }
  final artifacts = <_Artifact>[];
  await for (final entity
      in outputs.list(recursive: true, followLinks: false)) {
    if (entity is! File) {
      continue;
    }
    final path = entity.path.toLowerCase();
    if (path.endsWith('.apk') || path.endsWith('.aab')) {
      final dirs = fs.path
          .split(fs.path.relative(entity.parent.path, from: outputs.path))
          .where((d) => d != '.')
          .toList();
      artifacts.add(_Artifact(entity, await entity.lastModified(), dirs));
    }
  }
  artifacts.sort((a, b) => b.modified.compareTo(a.modified));
  return artifacts;
}

final _injectedMarkerBytes = ascii.encode(_injectedMarker);

Future<bool> _isInjectedByPlugin(File file) async {
  // Compare bytes: the file may not be valid UTF-8 if a user wrote it.
  final bytes = await file.readAsBytes();
  if (bytes.length < _injectedMarkerBytes.length) {
    return false;
  }
  for (var i = 0; i < _injectedMarkerBytes.length; i++) {
    if (bytes[i] != _injectedMarkerBytes[i]) {
      return false;
    }
  }
  return true;
}

const _sentryGradlePluginId = 'io.sentry.android.gradle';
final _applyFalse = RegExp(r'^[^\n]*?\bapply\s*\(?\s*false');

/// Returns the app module build file that applies the Sentry Android Gradle
/// Plugin, or null. Only the app module is checked: `settings.gradle` and the
/// root `build.gradle` usually just declare plugins (`apply false`). Handles
/// the plugin id, `apply plugin:`, and version catalog aliases
/// (`alias(libs.plugins.<name>)`).
Future<String?> _findSentryGradlePlugin(FileSystem fs) async {
  final references = [
    RegExp('''['"]${RegExp.escape(_sentryGradlePluginId)}['"]'''),
    for (final accessor in await _versionCatalogSentryAccessors(fs))
      RegExp('\\blibs\\.plugins\\.${RegExp.escape(accessor)}(?![\\w.])'),
  ];
  const candidates = [
    'android/app/build.gradle',
    'android/app/build.gradle.kts',
  ];
  for (final path in candidates) {
    final file = fs.file(path);
    if (!await file.exists()) {
      continue;
    }
    final source = _stripComments(
        utf8.decode(await file.readAsBytes(), allowMalformed: true));
    for (final reference in references) {
      for (final match in reference.allMatches(source)) {
        // `id("io.sentry.android.gradle") version "x" apply false` declares
        // the plugin without applying it.
        if (!_applyFalse.hasMatch(source.substring(match.end))) {
          return path;
        }
      }
    }
  }
  return null;
}

/// The `libs.plugins.*` accessors that the version catalog
/// (`android/gradle/libs.versions.toml`) maps to the Sentry Gradle plugin,
/// e.g. `sentry.android` for `sentry-android = { id = "io.sentry.android.gradle" }`.
Future<List<String>> _versionCatalogSentryAccessors(FileSystem fs) async {
  final file = fs.file('android/gradle/libs.versions.toml');
  if (!await file.exists()) {
    return const [];
  }
  final accessors = <String>[];
  var inPlugins = false;
  final lines = const LineSplitter()
      .convert(utf8.decode(await file.readAsBytes(), allowMalformed: true));
  for (final rawLine in lines) {
    final line = rawLine.trim();
    if (line.startsWith('[')) {
      inPlugins = line == '[plugins]';
      continue;
    }
    if (!inPlugins || line.startsWith('#')) {
      continue;
    }
    final match = RegExp(r'^([A-Za-z0-9_.-]+)\s*=\s*(.*)$').firstMatch(line);
    if (match != null && match.group(2)!.contains(_sentryGradlePluginId)) {
      accessors.add(match.group(1)!.replaceAll(RegExp('[-_]'), '.'));
    }
  }
  return accessors;
}

/// Removes `//` and `/* */` comments from Groovy/Kotlin [source], leaving
/// string literals (which may contain `//` or `/*`) intact.
String _stripComments(String source) {
  final out = StringBuffer();
  var i = 0;
  while (i < source.length) {
    final c = source[i];
    final next = i + 1 < source.length ? source[i + 1] : '';
    if (c == '/' && next == '/') {
      while (i < source.length && source[i] != '\n') {
        i++;
      }
    } else if (c == '/' && next == '*') {
      final end = source.indexOf('*/', i + 2);
      i = end == -1 ? source.length : end + 2;
      out.write(' ');
    } else if (c == '"' || c == "'") {
      final start = i;
      i++;
      while (i < source.length && source[i] != c && source[i] != '\n') {
        if (source[i] == r'\') {
          i++;
        }
        i++;
      }
      i++;
      out.write(source.substring(start, i.clamp(start, source.length)));
    } else {
      out.write(c);
      i++;
    }
  }
  return out.toString();
}
